const assert = require('assert')
const fs = require('fs')
const path = require('path')
const policy = require('../cloudfunctions/sample_workflow/samplePolicy')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

assert(policy.canTransition('draft', 'pending_factory_acceptance'))
assert(policy.canTransition('pending_factory_acceptance', 'sampling'))
assert(policy.canTransition('sampling', 'sample_completed'))
assert(policy.canTransition('sample_completed', 'pending_review'))
assert(policy.canTransition('pending_review', 'changes_requested'))
assert(policy.canTransition('changes_requested', 'resampling'))
assert(policy.canTransition('resampling', 'sample_completed'))
assert(policy.canTransition('pending_review', 'confirmed'))
assert(policy.canTransition('draft', 'cancelled'))
assert(!policy.canTransition('draft', 'confirmed'), 'draft cannot skip sample validation')
assert(!policy.canTransition('changes_requested', 'confirmed'), 'open revision cannot be confirmed')
assert(!policy.canTransition('confirmed', 'sampling'), 'confirmed history is immutable')
assert(policy.stableAsset('cloud://sample/photo.jpg'))
assert(policy.stableAsset('https://example.com/sample.jpg'))
assert(!policy.stableAsset('wxfile://tmp/photo.jpg'))
assert(!policy.stableAsset('http://tmp/photo.jpg'))

const cloudSource = read('cloudfunctions/sample_workflow/index.js')
assert(cloudSource.includes("version.reviewStatus !== 'approved'"), 'approved version is required')
assert(cloudSource.includes('master.approvedVersionId !== patternVersionId'), 'only current approved version is accepted')
assert(cloudSource.includes('idempotencyKey'), 'create supports an idempotency key')
assert(cloudSource.includes("id('sample_round')"), 'revision creates a new sample round')
assert(cloudSource.includes("status: 'open'"), 'concrete issues are persisted')
assert(cloudSource.includes('OPEN_ISSUES_EXIST'), 'confirmation rejects open issues')
assert(cloudSource.includes('SAMPLE_PHOTO_REQUIRED'), 'sample completion requires stable photos')
assert(cloudSource.includes('productionReady: false'), 'sample confirmation does not authorize production')
assert(!/createProductionOrder|productionOrderRepository|autoDelivery/.test(cloudSource), 'sample flow does not create production or delivery')
assert(!/event\.(openId|openid|_openid|role|isAdmin)/.test(cloudSource), 'client identity fields are not trusted')
assert(cloudSource.includes("session.status !== 'active'"), 'cloud session must be active')
assert(cloudSource.includes("member.status !== 'active'"), 'inactive member is rejected')

const pages = read('pages.json')
for (const route of ['sample-order-list/sample-order-list', 'sample-order-create/sample-order-create', 'sample-order-detail/sample-order-detail']) {
  assert(pages.includes(route), `${route} route is registered`)
}

const createPage = read('package-ai/sample-order-create/sample-order-create.vue')
const detailPage = read('package-ai/sample-order-detail/sample-order-detail.vue')
assert(createPage.includes('已批准') && createPage.includes('不会自动创建生产订单'))
assert(createPage.includes('idempotencyKey') && createPage.includes('submitting'))
assert(detailPage.includes("assetType: 'sample_image'"), 'sample photos use unified upload')
assert(detailPage.includes('修改轮次') && detailPage.includes('历史不可覆盖'))
assert(detailPage.includes('仍有未关闭') === false, 'raw backend error details are not hard-coded into the UI')
assert(!/openid|OPENID|sessionToken/.test(createPage + detailPage), 'sample pages do not display sensitive identity')

console.log('[PASS] sample state machine')
console.log('[PASS] approved pattern and tenant boundary')
console.log('[PASS] stable photo and immutable round contract')
console.log('[PASS] confirmation does not create production order')
console.log('[PASS] routes and sample UI contract')
