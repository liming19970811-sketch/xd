const assert = require('assert')
const fs = require('fs')
const path = require('path')
const policy = require('../cloudfunctions/pattern_review/reviewPolicy')

const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')

assert(policy.canReview('pattern_maker'), 'pattern_maker can review')
assert(policy.canReview('reviewer'), 'reviewer can review')
assert(policy.canReview('admin'), 'admin can review')
assert(!policy.canReview('owner'), 'owner cannot self-authorize as reviewer')
assert(!policy.canReview('viewer'), 'viewer is read only')
assert(policy.canTransition('ai_generated', 'under_review'), 'AI result can be submitted')
assert(policy.canTransition('under_review', 'changes_requested'), 'review can request changes')
assert(policy.canTransition('under_review', 'reviewed'), 'review checklist can complete review')
assert(policy.canTransition('reviewed', 'approved'), 'reviewed version can be approved')
assert(policy.canTransition('approved', 'archived'), 'approved version can be archived')
assert(!policy.canTransition('ai_generated', 'approved'), 'AI cannot approve directly')
assert(!policy.canTransition('approved', 'under_review'), 'approved history cannot be overwritten')
assert.deepStrictEqual(policy.approvedSafetyState(), { productionAvailable: false, factoryReady: false, sampleValidationStatus: 'not_started' })

const cloudSource = read('cloudfunctions/pattern_review/index.js')
assert(cloudSource.includes("getWXContext") === false, 'review authorization does not accept caller identity from page context')
assert(!/event\.(openId|openid|_openid|role|isAdmin)/.test(cloudSource), 'client identity fields are not trusted')
assert(cloudSource.includes("requireContext(event.sessionToken)"), 'cloud session is required')
assert(cloudSource.includes("member.status !== 'active'"), 'inactive members are rejected')
assert(cloudSource.includes("id('pattern_version')"), 'review edits create a new version')
assert(cloudSource.includes("resubmitting ? id('pattern_part')"), 'resubmission copies parts instead of overwriting history')
assert(cloudSource.includes('PATTERN_OUTPUT_REQUIRED'), 'empty AI output cannot be submitted')
assert(cloudSource.includes('REVIEW_CHECKLIST_INCOMPLETE'), 'dimensions and parts must be checked')
assert(cloudSource.includes('REVIEW_DATA_INCOMPLETE'), 'cloud verifies dimensions and parts exist')
assert(!/mock|fallback/i.test(cloudSource), 'review service does not fabricate review data')

const pages = read('pages.json')
assert(pages.includes('pattern-review-queue/pattern-review-queue'), 'queue route registered')
assert(pages.includes('pattern-review-detail/pattern-review-detail'), 'detail route registered')

const detail = read('package-ai/pattern-review-detail/pattern-review-detail.vue')
assert(detail.includes('尺寸复核') && detail.includes('纸样部件复核'), 'review detail contains both check areas')
assert(detail.includes('不代表样衣验证'), 'sample validation boundary is visible')
assert(!/openid|OPENID|sessionToken/.test(detail), 'sensitive identity is not displayed')

console.log('[PASS] trusted role policy')
console.log('[PASS] review state machine')
console.log('[PASS] immutable revision contract')
console.log('[PASS] production safety boundary')
console.log('[PASS] routes and review UI contract')
