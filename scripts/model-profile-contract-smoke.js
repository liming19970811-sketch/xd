const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { canAccessModelProfile } = require('../cloudfunctions/model_profile/accessPolicy')

const root = path.resolve(__dirname, '..')
const personal = { modelProfileId: 'profile_personal', scope: 'personal', ownerId: 'owner_a', status: 'active' }
const enterprise = { modelProfileId: 'profile_enterprise', scope: 'enterprise', enterpriseId: 'enterprise_a', status: 'active' }

assert.strictEqual(canAccessModelProfile(personal, { openId: 'owner_a' }), true)
assert.strictEqual(canAccessModelProfile(personal, { openId: 'owner_b' }), false)
assert.strictEqual(canAccessModelProfile(enterprise, { enterpriseId: 'enterprise_a', memberStatus: 'active', role: 'viewer' }, 'read'), true)
assert.strictEqual(canAccessModelProfile(enterprise, { enterpriseId: 'enterprise_b', memberStatus: 'active', role: 'admin' }, 'read'), false)
assert.strictEqual(canAccessModelProfile(enterprise, { enterpriseId: 'enterprise_a', memberStatus: 'disabled', role: 'admin' }, 'read'), false)
assert.strictEqual(canAccessModelProfile(enterprise, { enterpriseId: 'enterprise_a', memberStatus: 'active', role: 'viewer' }, 'manage'), false)
assert.strictEqual(canAccessModelProfile({ ...personal, status: 'deleted' }, { openId: 'owner_a' }), false)

